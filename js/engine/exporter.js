/**
 * データエクスポートモジュール
 * JSON形式、AI向けテキスト形式、CSV形式の出力生成を行う
 */

import { シュウケイ_サンシュツ } from "./aggregator.js";
import { モード_スイソク_サンシュツ } from "./mode_estimator.js";
import { セッテイ_スペック } from "../models/master_data.js";

export function ジェイソン_エクスポート(セッション) {
  const 集計 = シュウケイ_サンシュツ(セッション);
  const モード = モード_スイソク_サンシュツ(セッション.イベントリスト);

  const 出力オブジェクト = {
    スキーマバージョン: セッション.スキーマバージョン || "1.0.0",
    エクスポート日時: new Date().toISOString(),
    実戦メタ情報: {
      セッションID: セッション.セッションID,
      日付: セッション.日付,
      店舗名: セッション.店舗名,
      台番号: セッション.台番号,
      収支: セッション.収支情報
    },
    最新状況: 集計.最新状況,
    集計サマリー: 集計,
    モード推測状況: モード,
    引き継ぎスナップショット: セッション.初期スナップショット,
    イベント総数: セッション.イベントリスト.length,
    全イベント時系列: セッション.イベントリスト
  };

  return JSON.stringify(出力オブジェクト, null, 2);
}

/**
 * ChatGPT等のAIに直接貼り付けて分析・設定推測を依頼するためのテキストを生成する
 * @param {Object} セッション
 * @param {string} プロンプト種別 - '総合設定推測' | 'ヤメ時判断' | 'モード診断'
 */
export function エーアイ向けテキスト_生成(セッション, プロンプト種別 = "総合設定推測") {
  const 集計 = シュウケイ_サンシュツ(セッション);
  const モード = モード_スイソク_サンシュツ(セッション.イベントリスト);
  const 実戦 = 集計.実戦データ;
  const 引き継ぎ = 集計.引き継ぎデータ;
  const 合算 = 集計.合算トータル;
  const 示唆 = 集計.設定判別材料;

  let テキスト = `# 【スマスロ L東京喰種】実戦記録データ（AI設定分析用）\n\n`;
  テキスト += `## 1. 実戦概要\n`;
  テキスト += `- 日付: ${セッション.日付 || "未設定"}\n`;
  テキスト += `- 店舗: ${セッション.店舗名 || "未設定"} / 台番号: ${セッション.台番号 || "未設定"}\n`;
  テキスト += `- 現在の状況: 通常時 ${集計.最新状況.通常ゲーム数}G / ${集計.最新状況.ポイント数}pt / 状態: ${集計.最新状況.状態}\n`;
  テキスト += `- 投資: ${セッション.収支情報?.投資枚数 ?? 0}枚 / 回収: ${セッション.収支情報?.回収枚数 ?? 0}枚 / 差枚: ${セッション.収支情報?.差枚数 ?? 0}枚\n\n`;

  if (引き継ぎ.有効) {
    テキスト += `## 2. 引き継ぎデータ（打ち始め前カウンター値）\n`;
    テキスト += `- 前任者消化G数: ${引き継ぎ.通常ゲーム数}G\n`;
    テキスト += `- AT初当たり: ${引き継ぎ.AT初当たり回数}回\n`;
    テキスト += `- CZ突入: ${引き継ぎ.CZ突入回数}回（成功: ${引き継ぎ.CZ成功回数}回）\n\n`;
  }

  テキスト += `## 3. 実戦集計カウンター（自身で実際に観測・入力したデータ）\n`;
  テキスト += `※以下は前任者データを混ぜず、実際に打って記録した純粋な実戦データです。\n`;
  テキスト += `- 消化通常ゲーム数: ${実戦.通常ゲーム数}G\n`;
  テキスト += `- AT初当たり: ${実戦.AT初当たり回数}回 (確率: 1/${実戦.AT初当たり確率})\n`;
  テキスト += `  - 内訳: CZ成功 ${実戦.CZ成功回数}回 / レア役直撃 ${実戦.AT直撃回数}回 / 天井契機 ${実戦.AT天井回数}回 / エピソードボーナス ${実戦.エピソードボーナス回数}回\n`;
  テキスト += `- CZ突入合算: ${実戦.CZ突入回数}回 (確率: 1/${実戦.CZ確率} / 成功率: ${実戦.CZ成功率}%)\n`;
  テキスト += `  - レミニセンス: ${実戦.レミニセンス.突入}回 (成功: ${実戦.レミニセンス.成功}回 / 成功率: ${実戦.レミニセンス.成功率}%)\n`;
  テキスト += `  - 大喰いの利世（特大設定差）: ${実戦.大喰いの利世.突入}回 (確率: 1/${実戦.大喰いの利世.確率} / 成功: ${実戦.大喰いの利世.成功}回)\n`;
  テキスト += `- 100G以内のCZ当選率: ${実戦.当選100G以内.当選率}% (${実戦.当選100G以内.当選数} / ${実戦.当選100G以内.試行区間数}回) ※設定1=約19%〜設定6=約36%\n`;
  テキスト += `- AT引き戻し率: ${実戦.引き戻し.成功率}% (${実戦.引き戻し.成功回数} / ${実戦.引き戻し.試行回数}回)\n`;
  if (実戦.引き戻し.判定中回数 > 0) {
    テキスト += `  - ※現在引き戻し確認中（未確定）: ${実戦.引き戻し.判定中回数}回\n`;
  }
  テキスト += `- 精神世界ステージ:\n`;
  テキスト += `  - 突入回数: ${実戦.精神世界.突入回数}回\n`;
  テキスト += `  - 告知G数振り分け: 10G=${実戦.精神世界.告知G数振り分け["10G"]}回, 20G=${実戦.精神世界.告知G数振り分け["20G"]}回, 30G=${実戦.精神世界.告知G数振り分け["30G"]}回 (※30Gは設定6で大幅優遇)\n`;
  テキスト += `  - 消化中弱レア役CZ当選率: ${実戦.精神世界.弱レア役CZ当選率}% (${実戦.精神世界.弱レア役CZ当選回数} / ${実戦.精神世界.弱レア役回数}回)\n`;
  テキスト += `- 赫眼リプレイ成立回数: ${実戦.赫眼リプレイ.成立回数}回\n\n`;

  if (引き継ぎ.有効) {
    テキスト += `## 4. 全体合算データ（前任者＋自身）\n`;
    テキスト += `- 合算通常G数: ${合算.通常ゲーム数}G\n`;
    テキスト += `- 合算AT初当たり: ${合算.AT初当たり回数}回 (確率: 1/${合算.AT初当たり確率})\n`;
    テキスト += `- 合算CZ出現率: ${合算.CZ突入回数}回 (確率: 1/${合算.CZ確率})\n\n`;
  }

  テキスト += `## 5. 設定示唆・確定情報\n`;
  if (示唆.最小確定設定) {
    テキスト += `🔥 【確定情報】設定${示唆.最小確定設定}以上濃厚！\n`;
  }
  if (示唆.設定否定.length > 0) {
    テキスト += `❌ 【否定情報】設定${示唆.設定否定.join(", ")}否定\n`;
  }
  テキスト += `- 偶奇示唆: 偶数示唆 ${示唆.偶奇示唆.偶数示唆カウント}回 / 奇数示唆 ${示唆.偶奇示唆.奇数示唆カウント}回\n`;
  テキスト += `- 高設定示唆: 弱 ${示唆.高設定示唆.弱}回 / 強 ${示唆.高設定示唆.強}回\n`;

  if (示唆.終了画面履歴.length > 0) {
    テキスト += `### AT終了画面履歴\n`;
    示唆.終了画面履歴.forEach((h, idx) => {
      テキスト += `  ${idx + 1}. [${h.ゲーム数}G] ${h.画面名}\n`;
    });
  }

  if (示唆.CZカード履歴.length > 0) {
    テキスト += `### CZ終了PUSHカード履歴\n`;
    示唆.CZカード履歴.forEach((c, idx) => {
      テキスト += `  ${idx + 1}. [${c.ゲーム数}G] ${c.カード名} (${c.CZ種別})\n`;
    });
  }
  テキスト += `\n`;

  テキスト += `## 6. 現在のモード推測状況\n`;
  テキスト += `- 最有力モード: ${モード.最有力モード} ${モード.確定モード ? "【確定】" : "（推測）"}\n`;
  if (モード.有効候補.length > 0) {
    テキスト += `- 各モード候補と根拠:\n`;
    モード.有効候補.forEach(c => {
      テキスト += `  - ${c.モード名} (スコア: ${c.スコア}): ${c.理由.join(" / ") || "特記なし"}\n`;
    });
  }
  if (モード.警告.length > 0) {
    テキスト += `⚠️ 警告: ${モード.警告.join("、")}\n`;
  }
  テキスト += `\n`;

  テキスト += `## 7. 時系列実戦履歴ログ\n`;
  const ソート済みイベント = [...セッション.イベントリスト].sort((a, b) => {
    if (a.通常ゲーム数 !== b.通常ゲーム数) return a.通常ゲーム数 - b.通常ゲーム数;
    return (a.連番 || 0) - (b.連番 || 0);
  });

  if (ソート済みイベント.length === 0) {
    テキスト += `(イベント履歴なし)\n`;
  } else {
    for (const ev of ソート済みイベント) {
      const g = `${ev.通常ゲーム数 ?? 0}G`;
      const pt = ev.ポイント数 !== undefined ? ` [${ev.ポイント数}pt]` : "";
      テキスト += `${g}${pt} ${ev.タイトル}`;
      if (ev.詳細 && Object.keys(ev.詳細).length > 0) {
        const 詳細文字列 = Object.entries(ev.詳細)
          .map(([k, v]) => `${k}:${typeof v === "object" ? JSON.stringify(v) : v}`)
          .join(", ");
        テキスト += ` (${詳細文字列})`;
      }
      テキスト += `\n`;
    }
  }

  // 用途別プロンプトの切り替え
  テキスト += `\n---\n`;
  if (プロンプト種別 === "ヤメ時判断") {
    テキスト += `【AIへの依頼内容: ヤメ時・続行判断】
上記の実戦状況を踏まえ、現在（通常時${集計.最新状況.通常ゲーム数}G / ${集計.最新状況.ポイント数}pt / 状態: ${集計.最新状況.状態}）において：
1. 今すぐヤメるべきか、それとも次のゾーンや天井まで続行すべきか
2. 次の明確なヤメ時ライン（何ptまたは何Gまで回して前兆否定でヤメるべきか）
3. モード滞在推測から見た期待値判断
を分かりやすく端的にアドバイスしてください。
`;
  } else if (プロンプト種別 === "モード診断") {
    テキスト += `【AIへの依頼内容: モード精密診断】
これまでの前兆発生ポイント、月山招待状、アイキャッチ、CZ終了カードの履歴から：
1. 現在滞在している可能性が最も高いモードとその確率配分
2. 次回CZ当選期待度が高い規定ポイントゾーン
3. 天国やチャンスモードに滞在している強い根拠、または通常Aが濃厚となる懸念点
を詳しく解説してください。
`;
  } else {
    テキスト += `【AIへの依頼内容: 総合設定推測】
上記の実戦データに基づき、以下の点を詳細に考察・分析してください：
1. 推測される設定期待度ランキング（設定1〜6）とその明確な理由
2. 設定差の大きい要素（精神世界30G選択率、上位CZ大喰いの利世出現率、100G以内CZ当選率、引き戻し率、AT初当たり）の達成度評価
3. 偶数設定・奇数設定のどちらが濃いか、および高設定（4以上）期待度
4. 現時点での続行判断（押し・引きのアドバイス）
`;
  }

  return テキスト;
}

export function シーエスブイ_エクスポート(セッション) {
  const ヘッダー = ["連番", "ゲーム数", "ポイント数", "状態", "種別", "タイトル", "詳細内容"];
  const 行リスト = [ヘッダー.join(",")];

  const ソート済み = [...セッション.イベントリスト].sort((a, b) => {
    if (a.通常ゲーム数 !== b.通常ゲーム数) return a.通常ゲーム数 - b.通常ゲーム数;
    return (a.連番 || 0) - (b.連番 || 0);
  });

  for (const ev of ソート済み) {
    const 詳細文字 = ev.詳細 ? JSON.stringify(ev.詳細).replace(/"/g, '""') : "";
    const 行 = [
      ev.連番 ?? "",
      ev.通常ゲーム数 ?? 0,
      ev.ポイント数 ?? 0,
      ev.状態 ?? "",
      ev.種別 ?? "",
      `"${(ev.タイトル || "").replace(/"/g, '""')}"`,
      `"${詳細文字}"`
    ];
    行リスト.push(行.join(","));
  }

  return 行リスト.join("\r\n");
}
