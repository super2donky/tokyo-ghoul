/**
 * モード推測エンジン
 * ゾーン前兆、アイキャッチ、PUSHカード、招待状等の情報から現在の滞在モード候補を整理・推測する
 */

import { モード_マスター, CZ_プッシュカード_マスター, ショウタイジョウ_マスター, アイキャッチ_マスター } from "../models/master_data.js";
import { イベント種別 } from "../models/types.js";

/**
 * 実戦イベント群からモード滞在状況を推測する純粋関数
 * @param {Array} イベントリスト
 * @returns {Object} モード推測結果
 */
export function モード_スイソク_サンシュツ(イベントリスト) {
  if (!Array.isArray(イベントリスト) || イベントリスト.length === 0) {
    return デフォルトモード結果();
  }

  // 最新の区間（前回のCZ終了またはAT終了以降）のイベントのみを抽出
  let 最新区間イベント群 = [];
  for (let i = イベントリスト.length - 1; i >= 0; i--) {
    const ev = イベントリスト[i];
    最新区間イベント群.unshift(ev);
    if (ev.種別 === イベント種別.CZ結果 || ev.種別 === イベント種別.AT終了) {
      break;
    }
  }

  const モード候補 = {
    通常A: { スコア: 10, 確定: false, 否定: false, 理由: [] },
    通常B: { スコア: 10, 確定: false, 否定: false, 理由: [] },
    通常C: { スコア: 10, 確定: false, 否定: false, 理由: [] },
    チャンス: { スコア: 10, 確定: false, 否定: false, 理由: [] },
    天国準備: { スコア: 5, 確定: false, 否定: false, 理由: [] },
    天国: { スコア: 5, 確定: false, 否定: false, 理由: [] }
  };

  const 警告リスト = [];
  let 確定モード = null;
  let 天井示唆 = [];

  for (const イベント of 最新区間イベント群) {
    const 詳細 = イベント.詳細 || {};

    // 1. CZ終了時PUSHカード
    if (イベント.種別 === イベント種別.CZ結果 && 詳細.PUSHカード) {
      const カード名 = 詳細.PUSHカード;
      if (カード名 === "神代利世") {
        確定モード = "天国";
        モード候補.天国.確定 = true;
        モード候補.天国.理由.push("CZ終了カード「神代利世」により天国濃厚");
      } else if (カード名 === "月山習") {
        モード候補.天国準備.スコア += 80;
        モード候補.天国準備.理由.push("CZ終了カード「月山習」により天国準備以上濃厚");
        モード候補.天国.スコア += 50;
      } else if (カード名.includes("金木研（喰種）") || カード名.includes("霧嶋董香（喰種）")) {
        モード候補.チャンス.スコア += 60;
        モード候補.チャンス.理由.push("CZ終了カード「喰種」によりチャンス以上濃厚");
        モード候補.通常A.否定 = true;
      } else if (カード名 === "真戸呉緒") {
        モード候補.通常C.スコア += 50;
        モード候補.通常C.理由.push("CZ終了カード「真戸呉緒」により通常C以上濃厚");
        モード候補.通常A.否定 = true;
        モード候補.通常B.否定 = true;
      } else if (カード名 === "亜門鋼太朗") {
        モード候補.通常B.スコア += 40;
        モード候補.通常B.理由.push("CZ終了カード「亜門鋼太朗」により通常B以上濃厚");
        モード候補.通常A.否定 = true;
      } else if (カード名.includes("霧嶋董香") || カード名.includes("笛口雛実")) {
        モード候補.通常B.スコア += 20;
        モード候補.通常B.理由.push("CZ終了カードにより通常B以上示唆");
      }
    }

    // 2. ゾーン前兆・前兆情報（ちょんぼりすた解析完全連動）
    if (イベント.種別 === イベント種別.前兆情報 || イベント.種別 === イベント種別.ゾーン前兆 || (イベント.種別 === イベント種別.ポイント加算 && 詳細.前兆該当ゾーン)) {
      const ゾーン = 詳細.ゾーン || 詳細.該当ゾーン || 詳細.前兆該当ゾーン;
      const 前兆発生 = 詳細.前兆発生; // "あり" / "なし"
      const 東京上空 = 詳細.東京上空; // "あり" / "なし"

      const レア役重複 = 詳細.レア役重複 === true || 詳細.直前レア役影響 === "あり" || 詳細.レア役重複あり === true;

      if (ゾーン) {
        const ゾーン数値 = parseInt(ゾーン, 10);
        
        // 直前に強チェリー等のレア役を引いて前兆が重なっている場合、
        // ゾーン前兆や東京上空の有無によるモード断定を保留（誤判定防止）
        if (レア役重複) {
          警告リスト.push(`${ゾーン}前兆: 直前の強レア役等の影響（重複）が記録されているため、ゾーン前兆・東京上空によるモード断定は保留（参考扱い）としています。`);
          天井示唆.push(`${ゾーン}前兆: 直前レア役重複のためモード示唆は参考`);
          // 控えめなスコア加算のみ（モード否定や濃厚断定は一切行わない）
          if (!isNaN(ゾーン数値)) {
            const 百の位 = Math.floor(ゾーン数値 / 100);
            if (百の位 % 2 === 0) モード候補.通常A.スコア += 5;
            else モード候補.通常B.スコア += 5;
          }
        } else {
          // 純粋な単独ゾーン前兆の場合（ちょんぼりすた解析法則を適用）
          // 50Gゾーン: 前兆ありでチャンス以上、東京上空でCZ以上大チャンス
          if (ゾーン数値 === 50) {
            if (前兆発生 === "あり" || 前兆発生 === true) {
              モード候補.通常A.否定 = true;
              モード候補.通常B.否定 = true;
              モード候補.チャンス.スコア += 60;
              モード候補.チャンス.理由.push("50Gゾーン前兆発生（チャンス以上濃厚）");
              モード候補.天国準備.スコア += 60;
              モード候補.天国.スコア += 40;
              if (東京上空 === "あり" || 東京上空 === true) {
                天井示唆.push("50G東京上空移行: CZ以上の大チャンス！");
              }
            }
          }
          // 100Gゾーン: 東京上空なしで天国準備濃厚
          else if (ゾーン数値 === 100) {
            if (東京上空 === "なし" || 東京上空 === false) {
              モード候補.天国準備.スコア += 80;
              モード候補.天国準備.理由.push("100Gゾーンで東京上空非移行（天国準備濃厚！）");
              天井示唆.push("100G東京上空非移行: 天国準備濃厚！");
            }
          }
          // 150Gゾーン: 前兆ありで通常B以上濃厚、東京上空で本前兆濃厚
          else if (ゾーン数値 === 150) {
            if (前兆発生 === "あり" || 前兆発生 === true) {
              モード候補.通常A.否定 = true;
              モード候補.通常B.スコア += 50;
              モード候補.通常B.理由.push("150Gゾーン前兆発生（通常B以上濃厚）");
              モード候補.通常C.スコア += 50;
              モード候補.チャンス.スコア += 50;
            }
            if (東京上空 === "あり" || 東京上空 === true) {
              天井示唆.push("150G東京上空移行: 本前兆（CZ当選）濃厚！");
            }
          }
          // 200Gゾーン: 前兆なしで天国準備濃厚（天井300G）、東京上空なしで通常B以上期待度UP
          else if (ゾーン数値 === 200) {
            if (前兆発生 === "なし" || 前兆発生 === false) {
              モード候補.天国準備.スコア += 80;
              モード候補.天国準備.理由.push("200Gゾーン前兆非発生（天国準備濃厚！天井300G）");
              天井示唆.push("200G前兆なし: 天国準備濃厚（天井300G）");
            } else if (東京上空 === "なし" || 東京上空 === false) {
              モード候補.通常B.スコア += 30;
              モード候補.通常B.理由.push("200G東京上空非移行（通常B以上期待度UP）");
              モード候補.通常A.スコア -= 20;
            }
          }
          // 250Gゾーン: 前兆ありで通常C以上濃厚、東京上空で本前兆濃厚
          else if (ゾーン数値 === 250) {
            if (前兆発生 === "あり" || 前兆発生 === true) {
              モード候補.通常A.否定 = true;
              モード候補.通常B.否定 = true;
              モード候補.通常C.スコア += 60;
              モード候補.通常C.理由.push("250Gゾーン前兆発生（通常C以上濃厚）");
              モード候補.チャンス.スコア += 50;
            }
            if (東京上空 === "あり" || 東京上空 === true) {
              天井示唆.push("250G東京上空移行: 本前兆（CZ当選）濃厚！");
            }
          }
          // 300Gゾーン: 東京上空なしでチャンスモード濃厚
          else if (ゾーン数値 === 300) {
            if (東京上空 === "なし" || 東京上空 === false) {
              モード候補.チャンス.スコア += 80;
              モード候補.チャンス.理由.push("300Gゾーンで東京上空非移行（チャンスモード濃厚！）");
              天井示唆.push("300G東京上空非移行: チャンスモード濃厚！");
            }
          }

          // 百の位での汎用偶奇判定
          if (!isNaN(ゾーン数値)) {
            const 百の位 = Math.floor(ゾーン数値 / 100);
            if (百の位 % 2 === 0) {
              モード候補.通常A.スコア += 10;
            } else {
              モード候補.通常B.スコア += 10;
            }
          }
        }
      }

      // 東京上空ステージ演出（オーラ色・シャッター・チャンスアップ）
      if (詳細.オーラ色) {
        if (詳細.オーラ色.includes("赤") || 詳細.オーラ色 === "red") {
          天井示唆.push("東京上空 赤オーラ（期待度約95%！ハズレ時は次回高モード期待）");
        } else if (詳細.オーラ色.includes("白") || 詳細.オーラ色.includes("虹") || 詳細.オーラ色 === "white" || 詳細.オーラ色 === "rainbow") {
          天井示唆.push("東京上空 白/虹オーラ（本前兆濃厚！）");
        }
      }
      if (詳細.シャッター) {
        if (詳細.シャッター.includes("金") || 詳細.シャッター === "gold") {
          天井示唆.push("金シャッター出現（AT直撃・本前兆濃厚！）");
        } else if (詳細.シャッター.includes("赤") || 詳細.シャッター === "red") {
          天井示唆.push("赤シャッター出現（本前兆大チャンス）");
        }
      }
      if (詳細.チャンスアップ) {
        if (詳細.チャンスアップ.includes("デカPUSH") || 詳細.チャンスアップ === "deka_push") {
          天井示唆.push("デカPUSH出現（本前兆期待度激高）");
        } else if (詳細.チャンスアップ.includes("利世") || 詳細.チャンスアップ === "rize_voice") {
          天井示唆.push("赤PUSH/利世ボイス（大喰いの利世濃厚！）");
        }
      }
    }

    // 3. 示唆演出（月山招待状・アイキャッチ）ちょんぼりすた解析完全連動
    if (イベント.種別 === イベント種別.示唆演出) {
      if (詳細.演出名 === "月山招待状") {
        const セリフ = 詳細.セリフ || 詳細.内容;
        if (セリフ === "今すぐ僕のもとにきてくれ") {
          天井示唆.push("残り100G以内CZ濃厚（即ヤメ厳禁）");
          モード候補.天国.スコア += 70;
          モード候補.チャンス.スコア += 40;
        } else if (セリフ === "2時までに僕のもとにきてくれ") {
          天井示唆.push("残り200G以内CZ濃厚");
          モード候補.チャンス.スコア += 40;
        } else if (セリフ === "3時までに僕のもとにきてくれ") {
          天井示唆.push("残り300G以内CZ濃厚");
        } else if (セリフ === "心配しなくとも最悪の事態にはならないだろう") {
          天井示唆.push("600G天井否定");
          モード候補.通常A.スコア -= 10;
        }
      } else if (詳細.演出名 === "アイキャッチ") {
        const 名称 = 詳細.名称 || 詳細.内容;
        if (名称.includes("黒背景＋赫眼")) {
          天井示唆.push("黒背景赫眼アイキャッチ: 100G以内CZ当選濃厚！");
          モード候補.天国.スコア += 80;
        } else if (名称.includes("笛口雛実（白背景）")) {
          モード候補.通常C.スコア += 35;
          モード候補.通常C.理由.push("アイキャッチ雛実（通常C以上示唆）");
          モード候補.通常A.スコア -= 5;
        } else if (名称.includes("霧嶋董香（白背景）")) {
          モード候補.通常B.スコア += 25;
          モード候補.通常B.理由.push("アイキャッチ董香（通常B以上示唆）");
        } else if (名称.includes("月山習（白背景）") || 名称.includes("神代利世（白背景）")) {
          天井示唆.push("本前兆期待度大幅アップ");
        }
      }
    }
  }

  // 確定モードが存在する場合
  if (確定モード) {
    for (const キー of Object.keys(モード候補)) {
      if (キー !== 確定モード) {
        モード候補[キー].スコア = 0;
        モード候補[キー].否定 = true;
      }
    }
  }

  // 矛盾・競合チェック
  let 確定数 = 0;
  for (const キー of Object.keys(モード候補)) {
    if (モード候補[キー].確定) 確定数++;
  }
  if (確定数 > 1) {
    警告リスト.push("複数のモード確定示唆が競合しています。前兆や入力を再確認してください。");
  }

  const 有効候補 = Object.keys(モード候補)
    .filter(キー => !モード候補[キー].否定)
    .map(キー => ({
      モード名: キー,
      スコア: モード候補[キー].スコア,
      確定: モード候補[キー].確定,
      理由: モード候補[キー].理由
    }))
    .sort((a, b) => b.スコア - a.スコア);

  const 最有力モード = 確定モード ? 確定モード : (有効候補.length > 0 ? 有効候補[0].モード名 : "推測不能");

  return {
    確定モード,
    最有力モード,
    有効候補,
    天井示唆,
    警告: 警告リスト
  };
}

function デフォルトモード結果() {
  return {
    確定モード: null,
    最有力モード: "通常A",
    有効候補: [
      { モード名: "通常A", スコア: 10, 確定: false, 理由: ["初期状態"] },
      { モード名: "通常B", スコア: 10, 確定: false, 理由: ["初期状態"] },
      { モード名: "通常C", スコア: 10, 確定: false, 理由: ["初期状態"] },
      { モード名: "チャンス", スコア: 10, 確定: false, 理由: ["初期状態"] }
    ],
    天井示唆: [],
    警告: []
  };
}
